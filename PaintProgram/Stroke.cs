using Raylib_cs;

public class Stroke
{    
    public int X;
    public int Y;   
    public int radius;
    public Color color;

    public Stroke (int _X, int _Y, int _radius, Color _color)
    {
        
        X = _X;
        Y = _Y;
        radius = _radius;
        color = _color;

    }

}